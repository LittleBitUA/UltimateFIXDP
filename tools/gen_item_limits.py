#!/usr/bin/env python3
"""gen_item_limits.py ITEM.PRM > src/item_limits.h
How many of each item the game lets York own: UPDATA/PRM/ITEM.PRM (resource 39E0h; extract it with dpserial.py), records of DCh bytes
after a header (the game finds its end as in FUN_0044C060), +30h the most York may own in all (FUN_005019B0 refuses more: it answers -2).
"""
import struct, sys
d = open(sys.argv[1], "rb").read()
n0 = struct.unpack_from("<i", d, 0)[0]
base = n0 - ((n0 + 1) & 3) + 0xD
out = []
for i in range(366):
    v = struct.unpack_from("<i", d, base + i * 0xDC + 0x30)[0] if base + (i + 1) * 0xDC <= len(d) else 0
    out.append(max(0, min(v, 999)))
print("// Generated by tools/gen_item_limits.py from the game's UPDATA/PRM/ITEM.PRM: the most of each item York may own (0 = the game gives none).")
print("#pragma once")
print("constexpr unsigned short kItemMax[366] = {")
for i in range(0, 366, 24):
    print("    " + ", ".join(str(v) for v in out[i:i + 24]) + ",")
print("};")
